/// Table de décodage : octet lu → octet en clair.
pub(crate) const DECODE: [u8; 256] = {
    let mut decode = [0u8; 256];
    let mut plain = 0;
    while plain < 256 {
        decode[(TABLE[plain] ^ 8) as usize] = plain as u8;
        plain += 1;
    }
    decode
};

/// Table de codage (tests : fabrication de cellules).
#[cfg(test)]
pub(crate) const ENCODE: [u8; 256] = {
    let mut encode = [0u8; 256];
    let mut plain = 0;
    while plain < 256 {
        encode[plain] = TABLE[plain] ^ 8;
        plain += 1;
    }
    encode
};

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_inverse_permutations() {
        let mut seen = [false; 256];
        for (plain, &coded) in ENCODE.iter().enumerate() {
            assert!(!seen[coded as usize], "octet codé en double");
            seen[coded as usize] = true;
            assert_eq!(DECODE[coded as usize] as usize, plain);
        }
        // Le zéro, omniprésent dans les cellules, s'écrit 0xC5.
        assert_eq!(ENCODE[0], 0xC5);
    }
}
